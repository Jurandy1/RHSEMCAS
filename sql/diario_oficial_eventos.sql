-- Diário Oficial SEMCAS: histórico permanente e fluxo de conferência do RH.
-- Compatível com o plano gratuito do Supabase: apenas tabela, índices, trigger e view.

CREATE TABLE IF NOT EXISTS public.diario_oficial_eventos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id TEXT NOT NULL UNIQUE,
  acao TEXT NOT NULL CHECK (acao IN ('nomeacao', 'promocao', 'exoneracao')),
  nome TEXT,
  cargo TEXT,
  simbologia TEXT,
  data_ato DATE,
  data_publicacao DATE NOT NULL,
  edicao TEXT,
  titulo TEXT NOT NULL,
  link TEXT NOT NULL,
  funcionario_id BIGINT REFERENCES public.funcionarios(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'processado')),
  resultado TEXT,
  processado_por UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  processado_em TIMESTAMPTZ,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_diario_eventos_publicacao
  ON public.diario_oficial_eventos (data_publicacao DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_diario_eventos_pendentes
  ON public.diario_oficial_eventos (status, data_publicacao DESC);
CREATE INDEX IF NOT EXISTS idx_diario_eventos_funcionario
  ON public.diario_oficial_eventos (funcionario_id);

-- Normalização simples e imutável, sem depender de extensões pagas ou busca externa.
CREATE OR REPLACE FUNCTION public.diario_normalizar_nome(p_nome TEXT)
RETURNS TEXT
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
AS $$
  SELECT trim(regexp_replace(
    translate(upper(coalesce(p_nome, '')),
      'ÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇÑ',
      'AAAAAEEEEIIIIOOOOOUUUUCN'),
    '[^A-Z0-9]+', ' ', 'g'));
$$;

CREATE OR REPLACE FUNCTION public.diario_identificar_funcionario()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.funcionario_id IS NULL AND coalesce(NEW.nome, '') <> '' THEN
    SELECT f.id
      INTO NEW.funcionario_id
      FROM public.funcionarios f
     WHERE public.diario_normalizar_nome(f.nome) = public.diario_normalizar_nome(NEW.nome)
     ORDER BY coalesce(f.ativo, false) DESC, f.id DESC
     LIMIT 1;
  END IF;
  NEW.atualizado_em := NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_diario_identificar_funcionario ON public.diario_oficial_eventos;
CREATE TRIGGER trg_diario_identificar_funcionario
BEFORE INSERT OR UPDATE
ON public.diario_oficial_eventos
FOR EACH ROW EXECUTE FUNCTION public.diario_identificar_funcionario();

CREATE OR REPLACE VIEW public.v_diario_oficial_eventos
WITH (security_invoker = true)
AS
SELECT
  d.*,
  f.nome AS funcionario_nome,
  f.matricula AS funcionario_matricula,
  f.cargo AS funcionario_cargo,
  f.simbologia AS funcionario_simbologia,
  f.ativo AS funcionario_ativo
FROM public.diario_oficial_eventos d
LEFT JOIN public.funcionarios f ON f.id = d.funcionario_id;

ALTER TABLE public.diario_oficial_eventos ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS diario_eventos_select_auth ON public.diario_oficial_eventos;
CREATE POLICY diario_eventos_select_auth
ON public.diario_oficial_eventos FOR SELECT TO authenticated
USING (true);

DROP POLICY IF EXISTS diario_eventos_update_auth ON public.diario_oficial_eventos;
CREATE POLICY diario_eventos_update_auth
ON public.diario_oficial_eventos FOR UPDATE TO authenticated
USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS diario_eventos_insert_auth ON public.diario_oficial_eventos;
CREATE POLICY diario_eventos_insert_auth
ON public.diario_oficial_eventos FOR INSERT TO authenticated
WITH CHECK (true);

GRANT SELECT, INSERT, UPDATE ON public.diario_oficial_eventos TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.diario_oficial_eventos_id_seq TO authenticated;
GRANT SELECT ON public.v_diario_oficial_eventos TO authenticated;

COMMENT ON TABLE public.diario_oficial_eventos IS
  'Nomeações, promoções e exonerações da SEMCAS coletadas do Diário Oficial e conferidas pelo RH.';
